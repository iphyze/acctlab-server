function procurementReportBuildTransactionSheet(Spreadsheet $spreadsheet, string $title, array $rows, string $subtitle): void
{
    $sheet = $spreadsheet->createSheet();
    $safeTitle = substr($title, 0, 31);
    $sheet->setTitle($safeTitle);
    $sheet->getTabColor()->setRGB(PROCUREMENT_REPORT_TEAL);

    $headers = [
        'Date', 'PO / Purchase No.', 'Request No.', 'Supplier', 'Project', 'Scope', 'Invoice', 'Currency',
        'Procurement Value', 'Payable', 'Paid', 'Outstanding', 'WHT', 'Advance %', 'Workflow Status',
        'Payment Status', 'Account Status', 'PO Status', 'Officer', 'Received Date', 'Payment Date',
        'Aging Date', 'Age (Days)'
    ];
    procurementReportBrandSheet($sheet, strtoupper($title), $subtitle, count($headers), 6);
    $sheet->fromArray($headers, null, 'A6');

    $rowNumber = 7;
    foreach ($rows as $row) {
        $reference = trim((string) ($row['po_number'] ?? ''))
            ?: (trim((string) ($row['purchase_number'] ?? '')) ?: (string) ($row['request_number'] ?? ''));
        $project = trim((string) ($row['project_code'] ?? ''));
        $projectName = trim((string) ($row['project_name'] ?? ''));
        if ($project === '') {
            $project = $projectName;
        } elseif ($projectName !== '' && strcasecmp($project, $projectName) !== 0) {
            $project .= ' — ' . $projectName;
        }
        $sheet->fromArray([
            $row['request_date'] ?? null,
            $reference,
            $row['request_number'] ?? null,
            $row['supplier_name'] ?? 'Supplier not recorded',
            $project ?: null,
            $row['scope'] ?? null,
            $row['invoice_number'] ?? null,
            $row['currency'] ?? 'UNKNOWN',
            (float) ($row['procurement_value'] ?? 0),
            (float) ($row['payable_amount'] ?? 0),
            (float) ($row['paid_amount'] ?? 0),
            (float) ($row['outstanding_amount'] ?? 0),
            (float) ($row['wht_amount'] ?? 0),
            $row['advance_percentage'] === null ? null : (float) $row['advance_percentage'],
            $row['status'] ?? null,
            $row['payment_status'] ?? null,
            $row['account_status'] ?? null,
            $row['po_status'] ?? null,
            $row['officer'] ?? null,
            $row['received_date'] ?? null,
            $row['payment_date'] ?? null,
            $row['aging_date'] ?? null,
            (int) ($row['age_days'] ?? 0),
        ], null, 'A' . $rowNumber++);
    }

    $lastRow = max(7, $rowNumber - 1);
    procurementReportStyleRows($sheet, 7, $lastRow, count($headers));
    procurementReportMoneyFormat($sheet, "I7:M{$lastRow}");
    procurementReportPercentFormat($sheet, "N7:N{$lastRow}");
    procurementReportStatusStyle($sheet, 'O', 7, $lastRow);
    procurementReportStatusStyle($sheet, 'P', 7, $lastRow);
    procurementReportStatusStyle($sheet, 'Q', 7, $lastRow);
    $sheet->getStyle("H7:H{$lastRow}")->applyFromArray([
        'font' => ['bold' => true, 'color' => ['rgb' => PROCUREMENT_REPORT_TEAL_DARK]],
        'alignment' => ['horizontal' => Alignment::HORIZONTAL_CENTER],
    ]);
    procurementReportSetWidths($sheet, [
        'A' => 14, 'B' => 24, 'C' => 21, 'D' => 30, 'E' => 30, 'F' => 15, 'G' => 18, 'H' => 11,
        'I' => 19, 'J' => 18, 'K' => 18, 'L' => 18, 'M' => 17, 'N' => 12, 'O' => 19, 'P' => 18,
        'Q' => 18, 'R' => 17, 'S' => 24, 'T' => 16, 'U' => 16, 'V' => 16, 'W' => 12,
    ]);
    $sheet->getPageSetup()->setPrintArea("A1:W{$lastRow}");
    $sheet->getPageSetup()->setRowsToRepeatAtTopByStartAndEnd(1, 6);
}

try {
    if (strtoupper((string) ($_SERVER['REQUEST_METHOD'] ?? 'GET')) !== 'GET') {
        jsonResponse(['status' => 'Failed', 'message' => 'Method not allowed.'], 405);
    }

    $user = procurementRequireAnyPermission($conn, procurementSupplierActivityReportPermissionCodes());
    $reportQuery = $_GET;
    $reportQuery['page'] = 1;
    $reportQuery['limit'] = 1;
    $report = procurementSupplierActivityReport($conn, $user, $reportQuery);
    $total = (int) ($report['meta']['total'] ?? 0);
    if ($total > PROCUREMENT_REPORT_MAX_EXPORT_ROWS) {
        throw new RuntimeException(
            'The filtered report contains more than ' . number_format(PROCUREMENT_REPORT_MAX_EXPORT_ROWS) . ' rows. Narrow the filters before exporting.',
            422
        );
    }

    $visibleScopes = procurementSupplierActivityReportVisibleScopes($user);
    $filters = procurementSupplierActivityReportPrepareFilters($_GET, $visibleScopes);
    $base = procurementSupplierActivityReportBaseSql($filters['request_types']);
    $filtered = procurementSupplierActivityReportBuildWhere($filters);
    $types = $base['types'] . $filtered['types'];
    $params = array_merge($base['params'], $filtered['params']);
    $derived = '(' . $base['sql'] . ') report';
    $rows = procurementSupplierActivityReportFetchAll(
        $conn,
        "SELECT report.* FROM {$derived} WHERE {$filtered['sql']} ORDER BY report.request_date DESC, report.created_at DESC, report.canonical_id DESC LIMIT ?",
        $types . 'i',
        array_merge($params, [PROCUREMENT_REPORT_MAX_EXPORT_ROWS])
    );
    $rows = array_map('procurementSupplierActivityReportSerializeRow', $rows);

    if (!class_exists(Spreadsheet::class)) {
        throw new RuntimeException('Supplier Activity Excel export requires PhpSpreadsheet.', 500);
    }

    $spreadsheet = new Spreadsheet();
    $spreadsheet->getProperties()
        ->setCreator('ProcureDesk')
        ->setCompany('Lambert Electromec Limited')
        ->setTitle('Supplier Activity Report')
        ->setSubject(procurementReportSupplierLabel($report))
        ->setDescription('Filtered ProcureDesk supplier activity with currency-separated financial summaries.');

    procurementReportBuildSummarySheet($spreadsheet, $report, $rows);
    $subtitle = procurementReportSupplierLabel($report) . '  •  ' . number_format(count($rows)) . ' filtered transactions';
    procurementReportBuildTransactionSheet($spreadsheet, 'All Transactions', $rows, $subtitle);

    $byCurrency = [];
    foreach ($rows as $row) {
        $currency = strtoupper(trim((string) ($row['currency'] ?? ''))) ?: 'UNKNOWN';
        $byCurrency[$currency][] = $row;
    }
    if (count($byCurrency) > 1) {
        foreach ($byCurrency as $currency => $currencyRows) {
            procurementReportBuildTransactionSheet(
                $spreadsheet,
                preg_replace('/[^A-Z0-9 _-]/i', '', $currency) ?: 'Currency',
                $currencyRows,
                procurementReportSupplierLabel($report) . '  •  ' . $currency . '  •  ' . number_format(count($currencyRows)) . ' transactions'
            );
        }
    }

    $spreadsheet->setActiveSheetIndex(0);
    $supplierSlug = preg_replace('/[^A-Za-z0-9]+/', '-', procurementReportSupplierLabel($report));
    $supplierSlug = trim((string) $supplierSlug, '-') ?: 'All-Suppliers';
    $dateFrom = (string) ($report['meta']['filters']['date_from'] ?? '');
    $dateTo = (string) ($report['meta']['filters']['date_to'] ?? '');
    $periodSlug = $dateFrom !== '' || $dateTo !== ''
        ? (($dateFrom ?: 'Beginning') . '-to-' . ($dateTo ?: 'Present'))
        : 'All-Dates';
    $filename = 'ProcureDesk-Supplier-Activity-' . $supplierSlug . '-' . $periodSlug . '.xlsx';

    header('Content-Type: application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
    header('Content-Disposition: attachment; filename="' . $filename . '"');
    header('Cache-Control: private, no-store, max-age=0');
    header('X-Content-Type-Options: nosniff');
    $writer = new Xlsx($spreadsheet);
    $writer->save('php://output');
    $spreadsheet->disconnectWorksheets();
    exit;
} catch (Throwable $error) {
    $status = (int) $error->getCode();
    if ($status < 400 || $status > 599) {
        $status = 500;
    }
    if ($status >= 500) {
        error_log('ProcureDesk Supplier Activity Excel export error: ' . $error->getMessage());
    }
    jsonResponse([
        'status' => 'Failed',
        'message' => $status >= 500 ? 'Unable to export Supplier Activity Report.' : $error->getMessage(),
    ], $status);
}
