function procurementReportColumn(int $index): string
{
    return Coordinate::stringFromColumnIndex($index);
}

function procurementReportBrandSheet(
    Worksheet $sheet,
    string $title,
    string $subtitle,
    int $lastColumn,
    int $headerRow = 0
): void {
    $endColumn = procurementReportColumn($lastColumn);
    $sheet->setShowGridlines(false);
    $sheet->mergeCells("A1:{$endColumn}1");
    $sheet->mergeCells("A2:{$endColumn}2");
    $sheet->mergeCells("A3:{$endColumn}3");
    $sheet->setCellValue('A1', 'LAMBERT ELECTROMEC LIMITED  |  PROCUREDESK');
    $sheet->setCellValue('A2', $title);
    $sheet->setCellValue('A3', $subtitle);

    $sheet->getStyle("A1:{$endColumn}1")->applyFromArray([
        'font' => ['bold' => true, 'size' => 11, 'color' => ['rgb' => PROCUREMENT_REPORT_WHITE]],
        'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => PROCUREMENT_REPORT_TEAL_DARK]],
        'alignment' => ['horizontal' => Alignment::HORIZONTAL_LEFT, 'vertical' => Alignment::VERTICAL_CENTER],
    ]);
    $sheet->getStyle("A2:{$endColumn}2")->applyFromArray([
        'font' => ['bold' => true, 'size' => 20, 'color' => ['rgb' => PROCUREMENT_REPORT_WHITE]],
        'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => PROCUREMENT_REPORT_NAVY]],
        'alignment' => ['horizontal' => Alignment::HORIZONTAL_LEFT, 'vertical' => Alignment::VERTICAL_CENTER],
    ]);
    $sheet->getStyle("A3:{$endColumn}3")->applyFromArray([
        'font' => ['size' => 9, 'color' => ['rgb' => 'D7E7EC']],
        'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => PROCUREMENT_REPORT_NAVY_SOFT]],
        'alignment' => ['horizontal' => Alignment::HORIZONTAL_LEFT, 'vertical' => Alignment::VERTICAL_CENTER],
    ]);
    $sheet->getRowDimension(1)->setRowHeight(23);
    $sheet->getRowDimension(2)->setRowHeight(34);
    $sheet->getRowDimension(3)->setRowHeight(22);

    if ($headerRow > 0) {
        procurementReportStyleHeader($sheet, $headerRow, $lastColumn);
        $sheet->freezePane('A' . ($headerRow + 1));
        $sheet->setAutoFilter("A{$headerRow}:{$endColumn}{$headerRow}");
    }

    $sheet->getPageSetup()
        ->setOrientation(PageSetup::ORIENTATION_LANDSCAPE)
        ->setPaperSize(PageSetup::PAPERSIZE_A4)
        ->setFitToWidth(1)
        ->setFitToHeight(0);
    $sheet->getPageMargins()->setTop(0.45)->setBottom(0.45)->setLeft(0.3)->setRight(0.3);
    $sheet->getHeaderFooter()->setOddFooter('&LGenerated by ProcureDesk&CPage &P of &N&R' . date('Y-m-d H:i'));
}

function procurementReportStyleHeader(Worksheet $sheet, int $headerRow, int $lastColumn): void
{
    $endColumn = procurementReportColumn($lastColumn);
    $sheet->getStyle("A{$headerRow}:{$endColumn}{$headerRow}")->applyFromArray([
        'font' => ['bold' => true, 'size' => 9, 'color' => ['rgb' => PROCUREMENT_REPORT_WHITE]],
        'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => PROCUREMENT_REPORT_TEAL_DARK]],
        'alignment' => ['horizontal' => Alignment::HORIZONTAL_LEFT, 'vertical' => Alignment::VERTICAL_CENTER, 'wrapText' => true],
        'borders' => ['bottom' => ['borderStyle' => Border::BORDER_MEDIUM, 'color' => ['rgb' => PROCUREMENT_REPORT_TEAL]]],
    ]);
    $sheet->getRowDimension($headerRow)->setRowHeight(28);
}

function procurementReportStyleRows(Worksheet $sheet, int $firstRow, int $lastRow, int $lastColumn): void
{
    if ($lastRow < $firstRow) {
        return;
    }
    $endColumn = procurementReportColumn($lastColumn);
    $sheet->getStyle("A{$firstRow}:{$endColumn}{$lastRow}")->applyFromArray([
        'font' => ['size' => 9, 'color' => ['rgb' => PROCUREMENT_REPORT_TEXT]],
        'alignment' => ['vertical' => Alignment::VERTICAL_CENTER, 'wrapText' => true],
        'borders' => ['bottom' => ['borderStyle' => Border::BORDER_HAIR, 'color' => ['rgb' => PROCUREMENT_REPORT_BORDER]]],
    ]);
    for ($row = $firstRow; $row <= $lastRow; $row++) {
        $sheet->getRowDimension($row)->setRowHeight(24);
        if (($row - $firstRow) % 2 === 1) {
            $sheet->getStyle("A{$row}:{$endColumn}{$row}")->getFill()
                ->setFillType(Fill::FILL_SOLID)
                ->getStartColor()->setRGB('F4F9FA');
        }
    }
}

function procurementReportSetWidths(Worksheet $sheet, array $widths): void
{
    foreach ($widths as $column => $width) {
        $sheet->getColumnDimension($column)->setWidth($width);
    }
}

function procurementReportMoneyFormat(Worksheet $sheet, string $range): void
{
    $sheet->getStyle($range)->getNumberFormat()->setFormatCode('#,##0.00;[Red]-#,##0.00;–');
    $sheet->getStyle($range)->getAlignment()->setHorizontal(Alignment::HORIZONTAL_RIGHT);
}

function procurementReportPercentFormat(Worksheet $sheet, string $range): void
{
    $sheet->getStyle($range)->getNumberFormat()->setFormatCode('0.##"%"');
    $sheet->getStyle($range)->getAlignment()->setHorizontal(Alignment::HORIZONTAL_CENTER);
}

function procurementReportStatusStyle(Worksheet $sheet, string $column, int $firstRow, int $lastRow): void
{
    for ($row = $firstRow; $row <= $lastRow; $row++) {
        $status = strtolower(trim((string) $sheet->getCell($column . $row)->getValue()));
        if ($status === '') {
            continue;
        }
        $fill = PROCUREMENT_REPORT_BLUE_SOFT;
        $font = PROCUREMENT_REPORT_TEAL_DARK;
        if (str_contains($status, 'pending') || str_contains($status, 'processing')) {
            $fill = PROCUREMENT_REPORT_AMBER_SOFT;
            $font = '9A6500';
        } elseif (str_contains($status, 'paid') || str_contains($status, 'approved') || str_contains($status, 'account')) {
            $fill = PROCUREMENT_REPORT_GREEN_SOFT;
            $font = '2B966F';
        } elseif (str_contains($status, 'return') || str_contains($status, 'failed') || str_contains($status, 'cancel')) {
            $fill = PROCUREMENT_REPORT_RED_SOFT;
            $font = 'B84040';
        }
        $sheet->getStyle($column . $row)->applyFromArray([
            'font' => ['bold' => true, 'color' => ['rgb' => $font]],
            'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => $fill]],
            'alignment' => ['horizontal' => Alignment::HORIZONTAL_CENTER, 'vertical' => Alignment::VERTICAL_CENTER],
        ]);
    }
}

function procurementReportLabelList(array $values, string $allLabel = 'All'): string
{
    $clean = array_values(array_filter(array_map(static fn($value): string => trim((string) $value), $values)));
    return $clean === [] ? $allLabel : implode(', ', $clean);
}

function procurementReportDateBasisLabel(string $basis): string
{
    return match ($basis) {
        'request_date' => 'Request Date',
        'received_date' => 'Received Date',
        'payment_date' => 'Payment Date',
        default => 'All Date Bases',
    };
}

function procurementReportScopeLabel(string $scope): string
{
    return match ($scope) {
        'local_final' => 'Local Final',
        'local_advance' => 'Local Advance',
        'fx_final' => 'FX Final',
        'fx_advance' => 'FX Advance',
        default => 'All Scopes',
    };
}

function procurementReportSupplierLabel(array $report): string
{
    $supplierId = (int) ($report['meta']['filters']['supplier_id'] ?? 0);
    if ($supplierId <= 0) {
        return 'All Suppliers';
    }
    $label = trim((string) ($report['meta']['supplier_label'] ?? ''));
    return $label !== '' ? $label : 'Selected Supplier';
}

